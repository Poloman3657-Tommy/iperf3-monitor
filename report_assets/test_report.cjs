const assert = require('node:assert/strict');
const fs = require('node:fs');
assert.ok(fs.existsSync(__dirname+'/report.js'), 'Offline chart implementation is missing');
const {Viewport, timeUnit, selectPoints, nearestSample} = require('./report.js');
const v = new Viewport(345600);
v.focus(90000, 90002);
assert.deepEqual([v.left,v.right], [89995,90007]);
v.zoom(.5,90001); assert.deepEqual([v.left,v.right], [89998,90004]);
v.pan(-1e9); assert.deepEqual([v.left,v.right], [0,6]);
v.pan(1e9); assert.deepEqual([v.left,v.right], [345594,345600]);
v.zoom(1e-10,345600); assert.equal(v.right-v.left,1);
v.all(); assert.deepEqual([v.left,v.right], [0,345600]);
assert.equal(timeUnit('auto',59).factor,1);
assert.equal(timeUnit('auto',60).factor,60);
assert.equal(timeUnit('auto',3600).factor,3600);
assert.equal(timeUnit('auto',86400).factor,86400);
assert.equal(timeUnit('hours',1).factor,3600);
const samples = Array.from({length:345600},(_,i)=>[i,i+1,i===90000?0:i===100?999:500,i===90000?'LOW':'OK','']);
const overview = selectPoints(samples,0,345600);
assert.ok(overview.points.length<=4005);
assert.ok(overview.points.some(p=>p.row[2]===0));
assert.ok(overview.points.some(p=>p.row[2]===999));
assert.equal(samples.length,345600);
const detail=selectPoints(samples,89995,90007);
assert.equal(detail.overview,false);
assert.ok(detail.points.some(p=>p.index===90000));
assert.equal(nearestSample(samples,90000.5)[2],0);
const gaps=selectPoints([[0,1,50,'OK',''],[4,5,70,'OK','']],0,5);
assert.notEqual(gaps.points[0].group,gaps.points[1].group);
assert.equal(nearestSample([[0,1,1,'OK',''],[4,5,2,'OK','']],3),null);
assert.deepEqual(selectPoints([],0,1).points,[]);
console.log('HTML navigation, 4-day extrema, event focus, units and gaps passed');
